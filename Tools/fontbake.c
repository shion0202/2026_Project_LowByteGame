// One-off tool: bake exactly the glyphs the game draws into a C header.
//
// Not part of the game. The glyph set is read out of main.c rather than listed
// here, because a hand-kept list is a list that drifts: add one Korean line to
// the UI, forget to add its syllables, and that line renders as blank boxes in
// the shipped build with nothing to warn you.
//
//   fontbake.exe <ttf> <size> <out.h> <source.c> [more sources...]
//
// The output name decides the symbol ExportFontAsCode generates, so two sizes
// can live side by side: neodgm16.h gives LoadFont_Neodgm16, and so on. Small
// UI text and large headings are baked separately because one atlas cannot
// serve both - scaled far from its own size a pixel font turns to mush.
//
// Writes neodgm_baked.h next to the working directory and reports any
// requested codepoint the font has no glyph for, which is the check that
// matters: a missing glyph is silent at runtime.
#include "raylib.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>


// ExportFontAsCode writes its own banner with a "TODO: fill in the license"
// placeholder. Filling that in by hand works exactly once - the next bake
// overwrites it, and an OFL notice that disappears without anyone noticing is
// a licensing problem, not a cosmetic one. So the tool stamps it.
static void StampHeader(const char* path, const char* ttf, int size, int glyphs) {
    FILE* f = fopen(path, "rb");
    if (!f) return;
    fseek(f, 0, SEEK_END);
    long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    char* buf = (char*)malloc((size_t)n + 1);
    if (!buf) { fclose(f); return; }
    size_t got = fread(buf, 1, (size_t)n, f);
    buf[got] = '\0';
    fclose(f);

    // Cut from the TODO line to the end of the banner and write our own.
    const char* mark = "// TODO:";
    char* cut = strstr(buf, mark);
    const char* tail = cut ? strstr(cut, "////////") : NULL;
    if (!cut || !tail) { free(buf); return; }

    f = fopen(path, "wb");
    if (!f) { free(buf); return; }
    fwrite(buf, 1, (size_t)(cut - buf), f);

    // Just the file name. The absolute path is whatever machine last baked it,
    // which is noise in a checked-in file.
    const char* base = ttf;
    for (const char* p = ttf; *p; p++) if (*p == '/' || *p == '\\') base = p + 1;
    fprintf(f,
        "// Generated by tools/fontbake.c - do not edit.\n"
        "//\n"
        "// The glyph set is read out of main.c, so it always matches the text the\n"
        "// game actually draws. Re-bake after changing any UI string:\n"
        "//\n"
        "//     fontbake.exe <ttf> %d main.c\n"
        "//\n"
        "// Source:  %s\n"
        "// Size:    %dpx, %d glyphs\n"
        "//\n"
        "// Font:    Neo Dunggeunmo (neodgm)\n"
        "// Author:  Copyright (c) 2017-2024, Eunbin Jeong (Dalgona.)\n"
        "//          <project-neodgm@dalgona.dev>\n"
        "// License: SIL Open Font License 1.1\n"
        "//          Full text ships beside the exe as LICENSE-FONT.txt, which the\n"
        "//          OFL requires. Do not drop it from the distribution.\n"
        "//\n",
        size, base, size, glyphs);
    fwrite(tail, 1, strlen(tail), f);
    fclose(f);
    free(buf);
}

#define MAX_CP 8192
static int cps[MAX_CP];
static int cpCount;

static void AddCp(int c) {
    for (int i = 0; i < cpCount; i++) if (cps[i] == c) return;
    if (cpCount < MAX_CP) cps[cpCount++] = c;
}

// Minimal UTF-8 walk. Anything malformed is skipped rather than guessed at -
// this reads source files, so malformed input means the source is broken and
// silently inventing a codepoint would only hide that.
static void ScanUtf8(const unsigned char* p, long n) {
    for (long i = 0; i < n; ) {
        unsigned char b = p[i];
        int len, cp;
        if (b < 0x80) { len = 1; cp = b; }
        else if ((b & 0xE0) == 0xC0) { len = 2; cp = b & 0x1F; }
        else if ((b & 0xF0) == 0xE0) { len = 3; cp = b & 0x0F; }
        else if ((b & 0xF8) == 0xF0) { len = 4; cp = b & 0x07; }
        else { i++; continue; }
        if (i + len > n) break;
        for (int k = 1; k < len; k++) {
            if ((p[i + k] & 0xC0) != 0x80) { cp = -1; break; }
            cp = (cp << 6) | (p[i + k] & 0x3F);
        }
        i += len;
        // ASCII is added wholesale below; only non-ASCII is worth harvesting,
        // and control characters are never drawn.
        if (cp > 0x7F) AddCp(cp);
    }
}

static int ScanFile(const char* path) {
    FILE* f = fopen(path, "rb");
    if (!f) { printf("cannot open %s\n", path); return 0; }
    fseek(f, 0, SEEK_END);
    long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    unsigned char* buf = (unsigned char*)malloc((size_t)n);
    if (!buf) { fclose(f); return 0; }
    if (fread(buf, 1, (size_t)n, f) != (size_t)n) { free(buf); fclose(f); return 0; }
    ScanUtf8(buf, n);
    free(buf);
    fclose(f);
    return 1;
}

int main(int argc, char** argv) {
    if (argc < 5) {
        printf("usage: fontbake <ttf> <size> <out.h> <source.c> [more...]\n");
        return 1;
    }
    int fontSize = atoi(argv[2]);
    const char* outPath = argv[3];

    for (int c = 32; c < 127; c++) AddCp(c);
    int asciiCount = cpCount;
    for (int i = 4; i < argc; i++) if (!ScanFile(argv[i])) return 1;

    SetTraceLogLevel(LOG_WARNING);
    InitWindow(64, 64, "bake");

    Font f = LoadFontEx(argv[1], fontSize, cps, cpCount);
    if (f.glyphCount == 0) { printf("FAILED to load %s\n", argv[1]); return 1; }

    // raylib drops a codepoint the font has no glyph for rather than baking an
    // empty slot, so the check is against what was asked for, not what came
    // back. Naming them matters: at runtime a dropped codepoint draws as the
    // fallback box and nothing says why.
    int missing = 0;
    for (int i = 0; i < cpCount; i++) {
        int found = 0;
        for (int j = 0; j < f.glyphCount; j++)
            if (f.glyphs[j].value == cps[i]) { found = 1; break; }
        if (!found) { printf("  MISSING GLYPH U+%04X\n", cps[i]); missing++; }
    }

    ExportFontAsCode(f, outPath);
    StampHeader(outPath, argv[1], fontSize, f.glyphCount);

    printf("size=%d  ascii=%d  non-ascii=%d  total=%d  atlas=%dx%d  missing=%d\n",
        fontSize, asciiCount, cpCount - asciiCount, f.glyphCount,
        f.texture.width, f.texture.height, missing);

    UnloadFont(f);
    CloseWindow();
    return 0;
}
