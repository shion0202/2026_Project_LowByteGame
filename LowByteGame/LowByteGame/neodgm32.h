// Font loading function: Neodgm32
static Font LoadFont_Neodgm32(void)
{
    Font font = { 0 };

    font.baseSize = 32;
    font.glyphCount = 434;
    font.glyphPadding = 4;

    // Custom font loading
    // NOTE: Compressed font image data (DEFLATE), it requires DecompressData() function
    int fontDataSize_Neodgm32 = 0;
    unsigned char *data = DecompressData(fontData_Neodgm32, COMPRESSED_DATA_SIZE_FONT_NEODGM32, &fontDataSize_Neodgm32);
    Image imFont = { data, 1024, 1024, 1, 2 };

    // Load texture from image
    font.texture = LoadTextureFromImage(imFont);
    UnloadImage(imFont);  // Uncompressed data can be unloaded from memory

    // Assign glyph recs and info data directly
    // WARNING: This font data must not be unloaded
    font.recs = fontRecs_Neodgm32;
    font.glyphs = fontGlyphs_Neodgm32;

    return font;
}
